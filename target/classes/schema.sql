DROP TABLE IF EXISTS TURNO;
DROP TABLE IF EXISTS MASCOTA;
DROP TABLE IF EXISTS PERSONAL_MEDICO;
DROP TABLE IF EXISTS NIVEL_PRIORIDAD;

CREATE TABLE MASCOTA (
    id_mascota BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    especie VARCHAR(30) NOT NULL,
    raza VARCHAR(30),
    sexo VARCHAR(10)
);

CREATE TABLE PERSONAL_MEDICO (
    id_medico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    especialidad VARCHAR(50),
    tarjeta_profesional VARCHAR(20)
);

CREATE TABLE NIVEL_PRIORIDAD (
    id_prioridad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(30) NOT NULL,
    color_hex VARCHAR(10)
);

CREATE TABLE TURNO (
    id_turno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_turno VARCHAR(20) NOT NULL,
    id_mascota BIGINT NOT NULL,
    id_medico BIGINT,
    id_prioridad BIGINT NOT NULL,
    estado VARCHAR(20) DEFAULT 'EN_ESPERA',
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_mascota) REFERENCES MASCOTA(id_mascota),
    FOREIGN KEY (id_medico) REFERENCES PERSONAL_MEDICO(id_medico),
    FOREIGN KEY (id_prioridad) REFERENCES NIVEL_PRIORIDAD(id_prioridad)
);
